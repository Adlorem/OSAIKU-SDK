//! Discoverable native component contracts, shared by the compiler and report hosts.
//! Descriptions grant no authority and contain no host callbacks.
use crate::{Kind, Role};
use core::fmt::{self, Write};

pub const VERSION: u16 = 1;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DataType {
    Text,
    Percent,
    Series,
    Bool,
}
impl DataType {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Text => "text",
            Self::Percent => "percent",
            Self::Series => "series",
            Self::Bool => "bool",
        }
    }
    pub fn parse(name: &str) -> Option<Self> {
        [Self::Text, Self::Percent, Self::Series, Self::Bool]
            .into_iter()
            .find(|kind| kind.name() == name)
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Component {
    pub tag: &'static str,
    pub kind: Kind,
    pub role: Role,
}
macro_rules! components {
    ($(($tag:literal, $kind:ident, $role:ident)),+ $(,)?) => {
        pub const COMPONENTS: &[Component] = &[$(Component {
            tag: $tag, kind: Kind::$kind, role: Role::$role,
        }),+];
    };
}
components![
    ("main", Container, Group),
    ("section", Container, Group),
    ("header", Container, Group),
    ("footer", Container, Group),
    ("div", Container, Group),
    ("nav", Container, Navigation),
    ("thead", Container, Group),
    ("tbody", Container, Group),
    ("span", Text, Text),
    ("p", Text, Text),
    ("h1", Text, Heading),
    ("h2", Text, Heading),
    ("table", Table, Table),
    ("tr", Row, Row),
    ("ui-list-item", Row, Row),
    ("td", Cell, Cell),
    ("th", Cell, ColumnHeader),
    ("button", Button, Button),
    ("ui-text-input", TextInput, TextBox),
    ("ui-virtual-list", VirtualList, Group),
    ("template", Template, Group),
    ("ui-chart", Chart, Chart),
    ("ui-value-bar", ValueBar, Meter),
    ("ui-separator", Separator, Separator),
    ("ui-icon", Icon, Presentation),
];
pub fn component(tag: &str) -> Option<&'static Component> {
    COMPONENTS.iter().find(|entry| entry.tag == tag)
}
pub const fn actionable(kind: Kind) -> bool {
    matches!(kind, Kind::Button | Kind::Row | Kind::TextInput)
}

#[derive(Clone, Copy, Debug)]
pub struct Binding {
    pub attribute: &'static str,
    pub slot: usize,
    pub data_type: DataType,
}
impl Binding {
    pub fn accepts(self, kind: Kind) -> bool {
        match self.data_type {
            DataType::Text => !kind.container(),
            DataType::Percent => kind == Kind::ValueBar,
            DataType::Series => kind == Kind::Chart,
            DataType::Bool => true,
        }
    }
}
pub const BINDINGS: &[Binding] = &[
    Binding {
        attribute: "bind:text",
        slot: 0,
        data_type: DataType::Text,
    },
    Binding {
        attribute: "bind:value",
        slot: 1,
        data_type: DataType::Percent,
    },
    Binding {
        attribute: "bind:series",
        slot: 2,
        data_type: DataType::Series,
    },
    Binding {
        attribute: "bind:hidden",
        slot: 3,
        data_type: DataType::Bool,
    },
    Binding {
        attribute: "bind:disabled",
        slot: 4,
        data_type: DataType::Bool,
    },
    Binding {
        attribute: "bind:selected",
        slot: 5,
        data_type: DataType::Bool,
    },
];
pub fn binding(attribute: &str) -> Option<&'static Binding> {
    BINDINGS.iter().find(|entry| entry.attribute == attribute)
}

/// Application-local report intentions. The host authenticates and dispatches
/// input against its presented revision; an action name is never a capability.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ActionKind {
    Refresh,
    Sort,
    Filter,
    Select,
    Navigate,
    InspectSource,
    Close,
}
impl ActionKind {
    pub const ALL: [Self; 7] = [
        Self::Refresh,
        Self::Sort,
        Self::Filter,
        Self::Select,
        Self::Navigate,
        Self::InspectSource,
        Self::Close,
    ];
    pub const fn name(self) -> &'static str {
        match self {
            Self::Refresh => "refresh",
            Self::Sort => "sort",
            Self::Filter => "filter",
            Self::Select => "select",
            Self::Navigate => "navigate",
            Self::InspectSource => "inspect-source",
            Self::Close => "close",
        }
    }
    pub fn parse(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|kind| kind.name() == name)
    }
}

/// Generate the reference from the descriptors used by compilation/admission.
pub fn write_reference(out: &mut impl Write) -> fmt::Result {
    writeln!(out, "# Native UI catalog v{}\n\nGenerated by `osaiku-ui-compile --catalog`; do not edit.\n\nDocument wire major: {}. Catalog versions are exact-match.\n", VERSION, crate::VERSION)?;
    writeln!(
        out,
        "## Components\n\n| Tag | Kind | Semantic role | Action |\n| --- | --- | --- | --- |"
    )?;
    for c in COMPONENTS {
        writeln!(
            out,
            "| `{}` | {:?} | {:?} | {} |",
            c.tag,
            c.kind,
            c.role,
            actionable(c.kind)
        )?;
    }
    writeln!(
        out,
        "\n## Typed bindings\n\n| Attribute | Type | Targets |\n| --- | --- | --- |"
    )?;
    for b in BINDINGS {
        let targets = match b.data_type {
            DataType::Text => "Leaves",
            DataType::Percent => "ui-value-bar",
            DataType::Series => "ui-chart",
            DataType::Bool => "Any node",
        };
        writeln!(
            out,
            "| `{}` | {} | {} |",
            b.attribute,
            b.data_type.name(),
            targets
        )?;
    }
    writeln!(out, "\nText is literal UTF-8 (at most {} bytes per leaf). Percent is optional,\n0..10000 basis points; unavailable is distinct from zero. Series contain at\nmost 60 ordered timestamped percent samples, including explicit missing samples.\nBool controls hidden/disabled/selected state.\n", crate::MAX_LEAF_TEXT)?;
    writeln!(
        out,
        "## Report actions\n\n| Intent | Authority |\n| --- | --- |"
    )?;
    for action in ActionKind::ALL {
        writeln!(
            out,
            "| `{}` | Application-local; no OS capability |",
            action.name()
        )?;
    }
    writeln!(out, "\n## Source registration\n\nHosts register named, versioned `record` or `rows` schemas. Fields have a source\nand one of the binding types above. Row fields belong to the matching virtual-list\nprototype or materialized rows; record fields belong outside those rows.\nSource names and schema versions do not authorize queries or disclosure.\nReport input must be checked against the host's registered contract before binding.\n")?;
    writeln!(out, "## Limits\n\nNodes: {}; depth: {}; text bytes: {}; series points: {}; wire bytes: {}.\nReport sources: {}; fields: {}; actions: {}.\n\nThe catalog describes existing native primitives, not browser HTML/CSS.\nSee [UI format](ui-v1.md) for styles, attributes and structural restrictions.", crate::MAX_NODES, crate::MAX_DEPTH, crate::MAX_TEXT, crate::MAX_POINTS, crate::MAX_WIRE,
        crate::report::MAX_SOURCES, crate::report::MAX_FIELDS, crate::report::MAX_ACTIONS)
}
