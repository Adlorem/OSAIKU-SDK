//! Host-registered schemas for generated reports. Allocation-free admission;
//! the same document wire and compiler are used by packaged native apps.
//! Names/schema declarations are not permission to read a source or run an action.
use crate::{
    catalog::{self, ActionKind, DataType},
    symbol, Document, Kind, NONE,
};

pub const MAX_SOURCES: usize = 16;
pub const MAX_FIELDS: usize = 128;
pub const MAX_ACTIONS: usize = 64;
pub mod host;
pub mod region;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shape {
    Record,
    Rows,
}
#[derive(Clone, Copy, Debug)]
pub struct Source<'a> {
    pub name: &'a str,
    pub schema_version: u16,
    pub shape: Shape,
}
#[derive(Clone, Copy, Debug)]
pub struct Field<'a> {
    pub name: &'a str,
    pub source: &'a str,
    pub data_type: DataType,
}
#[derive(Clone, Copy, Debug)]
pub struct Action<'a> {
    pub name: &'a str,
    pub kind: ActionKind,
}
#[derive(Clone, Copy, Debug)]
pub struct Contract<'a> {
    pub catalog_version: u16,
    pub wire_version: u16,
    pub sources: &'a [Source<'a>],
    pub fields: &'a [Field<'a>],
    pub actions: &'a [Action<'a>],
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    Version,
    Limit,
    Name,
    Duplicate,
    UnknownSource,
    UnknownField,
    UnknownAction,
    Type,
    Scope,
    Document(crate::Error),
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReferenceError {
    Contract(Error),
    Write(core::fmt::Error),
}
impl From<core::fmt::Error> for ReferenceError {
    fn from(error: core::fmt::Error) -> Self {
        Self::Write(error)
    }
}
pub fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && symbol(name) != 0
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"-_.".contains(&b))
}
impl Contract<'_> {
    /// Generate the host's data/action reference from its admitted schema.
    pub fn write_reference(&self, out: &mut impl core::fmt::Write) -> Result<(), ReferenceError> {
        self.validate().map_err(ReferenceError::Contract)?;
        writeln!(out, "# Registered report contract\n\nGenerated by `osaiku-ui-compile --describe`; do not edit.\n\nCatalog: {}; document wire: {}.\n", self.catalog_version, self.wire_version)?;
        writeln!(
            out,
            "## Sources\n\n| Name | Shape | Schema version |\n| --- | --- | --- |"
        )?;
        for s in self.sources {
            writeln!(
                out,
                "| `{}` | {:?} | {} |",
                s.name, s.shape, s.schema_version
            )?;
        }
        writeln!(
            out,
            "\n## Fields\n\n| Source | Field | Type | Symbol |\n| --- | --- | --- | --- |"
        )?;
        for f in self.fields {
            writeln!(
                out,
                "| `{}` | `{}` | {} | `{:08x}` |",
                f.source,
                f.name,
                f.data_type.name(),
                symbol(f.name)
            )?;
        }
        writeln!(
            out,
            "\n## Actions\n\n| Name | Intent | Symbol |\n| --- | --- | --- |"
        )?;
        for a in self.actions {
            writeln!(
                out,
                "| `{}` | {} | `{:08x}` |",
                a.name,
                a.kind.name(),
                symbol(a.name)
            )?;
        }
        writeln!(out, "\nThese registrations describe local bindings and intentions; they grant no query,\ndisclosure or execution permission. The host supplies this contract, validates\nthe document, authenticates input and enforces source access separately.")?;
        Ok(())
    }
    pub fn validate(&self) -> Result<(), Error> {
        if self.catalog_version != catalog::VERSION || self.wire_version != crate::VERSION {
            return Err(Error::Version);
        }
        if self.sources.len() > MAX_SOURCES
            || self.fields.len() > MAX_FIELDS
            || self.actions.len() > MAX_ACTIONS
        {
            return Err(Error::Limit);
        }
        // Names share the compiler's symbol namespace. Equal spellings across
        // categories are allowed; distinct spellings with equal hashes are not.
        let names = || {
            self.sources
                .iter()
                .map(|s| s.name)
                .chain(self.fields.iter().map(|f| f.name))
                .chain(self.actions.iter().map(|a| a.name))
        };
        for (index, name) in names().enumerate() {
            if !valid_name(name) {
                return Err(Error::Name);
            }
            if names()
                .take(index)
                .any(|old| old != name && symbol(old) == symbol(name))
            {
                return Err(Error::Duplicate);
            }
        }
        for (i, source) in self.sources.iter().enumerate() {
            if source.schema_version == 0 {
                return Err(Error::Version);
            }
            if self.sources[..i].iter().any(|s| s.name == source.name) {
                return Err(Error::Duplicate);
            }
        }
        for (i, field) in self.fields.iter().enumerate() {
            let source = self
                .sources
                .iter()
                .find(|s| s.name == field.source)
                .ok_or(Error::UnknownSource)?;
            if self.fields[..i].iter().any(|f| {
                f.name == field.name
                    && (f.source == field.source
                        || (source.shape == Shape::Record
                            && self
                                .sources
                                .iter()
                                .any(|s| s.name == f.source && s.shape == Shape::Record)))
            }) {
                return Err(Error::Duplicate);
            }
        }
        for (i, action) in self.actions.iter().enumerate() {
            if self.actions[..i].iter().any(|a| a.name == action.name) {
                return Err(Error::Duplicate);
            }
        }
        Ok(())
    }

    /// Validate a decoded or compiled recipe before resolving any provider.
    pub fn validate_document(&self, document: &Document) -> Result<(), Error> {
        self.validate()?;
        document.validate().map_err(Error::Document)?;
        for node in &document.nodes[..document.len as usize] {
            if node.action != 0 && !self.actions.iter().any(|a| symbol(a.name) == node.action) {
                return Err(Error::UnknownAction);
            }
            if node.kind == Kind::VirtualList {
                let id = document.lists[node.value as usize].source;
                let source = self
                    .sources
                    .iter()
                    .find(|s| symbol(s.name) == id)
                    .ok_or(Error::UnknownSource)?;
                if source.shape != Shape::Rows {
                    return Err(Error::Scope);
                }
            }
            let mut current = node.parent;
            let mut row_source = None;
            while current != NONE {
                let ancestor = &document.nodes[current as usize];
                // The same source scope applies before and after virtual-list
                // realization, which removes the Template wrapper.
                if ancestor.kind == Kind::VirtualList {
                    row_source = Some(document.lists[ancestor.value as usize].source);
                    break;
                }
                current = ancestor.parent;
            }
            for binding in catalog::BINDINGS {
                let key = node.bindings[binding.slot];
                if key == 0 {
                    continue;
                }
                let mut candidates = self
                    .fields
                    .iter()
                    .filter(|f| symbol(f.name) == key)
                    .peekable();
                if candidates.peek().is_none() {
                    return Err(Error::UnknownField);
                }
                let field = candidates
                    .find(|f| {
                        self.sources.iter().any(|s| {
                            s.name == f.source
                                && match row_source {
                                    Some(id) => s.shape == Shape::Rows && symbol(s.name) == id,
                                    None => s.shape == Shape::Record,
                                }
                        })
                    })
                    .ok_or(Error::Scope)?;
                if field.data_type != binding.data_type || !binding.accepts(node.kind) {
                    return Err(Error::Type);
                }
            }
        }
        Ok(())
    }

    /// Resolve only registered report intentions. Authenticate the original
    /// event and presented revision before dispatching the returned kind.
    pub fn action(&self, id: u32) -> Result<ActionKind, Error> {
        self.validate()?;
        self.actions
            .iter()
            .find(|a| symbol(a.name) == id)
            .map(|a| a.kind)
            .ok_or(Error::UnknownAction)
    }
}

